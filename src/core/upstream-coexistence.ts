/**
 * Removes command files for renamed legacy QASpec workflow ids.
 */
export async function removeRenamedQaspecCommandFiles(
  projectPath: string,
  toolId: string
): Promise<number> {
  let removed = 0;
  const adapter = CommandAdapterRegistry.get(toolId);
  if (!adapter) return 0;

  for (const legacyId of Object.keys(RENAMED_QAS_WORKFLOW_IDS)) {
    const cmdPath = adapter.getFilePath(legacyId);
    const fullPath = path.isAbsolute(cmdPath) ? cmdPath : path.join(projectPath, cmdPath);
    try {
      if (fs.existsSync(fullPath)) {
        await fs.promises.unlink(fullPath);
        removed++;
      }
    } catch {
      // Ignore errors
    }
  }
  return removed;
}

