/**
 * Per-file coexistence when upstream OpenSpec is already installed.
 * Preserves existing upstream openspec-* skills and opsx-* commands.
 */

import fs from 'node:fs';
import path from 'path';
import { FileSystemUtils } from '../utils/file-system.js';
import { detectLegacySlashCommands } from './legacy-cleanup.js';
import { qasCommandSubdir, qaspecSkillDirName } from './qaspec-commands.js';
import { RETIRED_QAS_WORKFLOW_IDS, RENAMED_QAS_WORKFLOW_IDS } from './profiles.js';
import { CommandAdapterRegistry } from './command-generation/index.js';

/** Upstream OpenSpec skill directory names (not generated by QASpec). */
export const UPSTREAM_OPENSPEC_SKILL_NAMES = [
  'openspec-explore',
  'openspec-new-change',
  'openspec-continue-change',
  'openspec-apply-change',
  'openspec-ff-change',
  'openspec-sync-specs',
  'openspec-archive-change',
  'openspec-bulk-archive-change',
  'openspec-verify-change',
  'openspec-onboard',
  'openspec-propose',
] as const;

/** Workflow IDs whose opsx-* commands belong to upstream OpenSpec. */
export const UPSTREAM_LEGACY_WORKFLOW_IDS = [
  'new',
  'continue',
  'apply',
  'ff',
  'sync',
  'bulk-archive',
  'verify',
  'onboard',
  'propose',
] as const;

const upstreamSkillDirs = new Set<string>(UPSTREAM_OPENSPEC_SKILL_NAMES);
const upstreamWorkflowIds = new Set<string>(UPSTREAM_LEGACY_WORKFLOW_IDS);

export function formatUpstreamCoexistenceSummary(preservedSkills: number, preservedCommands: number): string {
  if (preservedSkills === 0 && preservedCommands === 0) {
    return '';
  }
  const parts: string[] = [];
  if (preservedSkills > 0) {
    parts.push(`${preservedSkills} existing upstream openspec-* skill${preservedSkills === 1 ? '' : 's'}`);
  }
  if (preservedCommands > 0) {
    parts.push(`${preservedCommands} existing upstream opsx-* command${preservedCommands === 1 ? '' : 's'}`);
  }
  return `Upstream OpenSpec detected — preserved ${parts.join(' and ')}`;
}

export async function shouldSkipUpstreamSkillWrite(
  skillFilePath: string,
  dirName: string,
  upstreamActive: boolean
): Promise<boolean> {
  if (!upstreamActive || !upstreamSkillDirs.has(dirName)) {
    return false;
  }
  return FileSystemUtils.fileExists(skillFilePath);
}

export async function shouldSkipUpstreamCommandWrite(
  commandFilePath: string,
  commandId: string,
  upstreamActive: boolean
): Promise<boolean> {
  if (!upstreamActive || !upstreamWorkflowIds.has(commandId)) {
    return false;
  }
  return FileSystemUtils.fileExists(commandFilePath);
}

export function isUpstreamOpenspecSkillDir(dirName: string): boolean {
  return upstreamSkillDirs.has(dirName);
}

export function isUpstreamLegacyWorkflow(workflow: string): boolean {
  return upstreamWorkflowIds.has(workflow);
}

/**
 * Removes legacy QASpec-installed openspec-* skill directories when upstream is not active.
 */
export async function removeLegacyQaspecSkillDirs(
  skillsDir: string,
  upstreamOpenSpecActive: boolean
): Promise<number> {
  if (upstreamOpenSpecActive) {
    return 0;
  }

  let removed = 0;
  for (const dirName of UPSTREAM_OPENSPEC_SKILL_NAMES) {
    const skillDir = path.join(skillsDir, dirName);
    try {
      if (fs.existsSync(skillDir)) {
        await fs.promises.rm(skillDir, { recursive: true, force: true });
        removed++;
      }
    } catch {
      // Ignore errors
    }
  }

  return removed;
}

/**
 * Removes legacy QASpec-installed slash command files when upstream is not active.
 */
export async function removeLegacyQaspecCommandFiles(
  projectPath: string,
  upstreamOpenSpecActive: boolean
): Promise<number> {
  if (upstreamOpenSpecActive) {
    return 0;
  }

  const slashResult = await detectLegacySlashCommands(projectPath);

  let removed = 0;
  for (const relativePath of slashResult.files) {
    const base = path.basename(relativePath);
    if (!base.startsWith('opsx-') && !base.startsWith('openspec-')) {
      continue;
    }
    const fullPath = path.join(projectPath, relativePath);
    try {
      if (fs.existsSync(fullPath)) {
        await fs.promises.unlink(fullPath);
        removed++;
      }
    } catch {
      // Ignore errors
    }
  }

  return removed;
}

/**
 * Removes skill directories for retired QASpec workflow ids (e.g. qaspec-explore).
 */
